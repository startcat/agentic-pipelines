import { describe, expect, test } from 'bun:test';
import { launchdBackend } from '../../src/install/launchd-backend.ts';
import { cronToCalendarIntervals } from '../../src/install/common.ts';

/**
 * Golden test of the plist: the systemd backend must not change anything on
 * macOS. The literal below was generated with
 * `renderPlist(buildPlistSpec(…))` BEFORE moving launchd behind
 * `SchedulerBackend`, and is not touched: if this test fails, the plist that
 * is written on the Macs has changed, and that is not a refactor.
 * (Only the header comment inside the plist was translated to English; it is
 * inert for launchd and ignored by the drift comparison.)
 */
const EXPECTED_PLIST = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
  '<!--',
  '  GENERATED BY `pipelines install` — DO NOT EDIT BY HAND.',
  '  Source:    /repo with space/pipelines/demo/pipeline.yaml',
  '  Generated: 2026-10-27T10:00:00.000Z',
  '',
  '  To change the schedule, edit `triggers.cron` in that file and run',
  '  `pipelines install` again. To change a parameter, edit',
  '  `.params.local.json` in the data repo: this plist carries none.',
  '-->',
  '<plist version="1.0">',
  '<dict>',
  '\t<key>Label</key>',
  '\t<string>cat.start.pipelines.demo</string>',
  '',
  '\t<key>ProgramArguments</key>',
  '\t<array>',
  '\t\t<string>/usr/local/bin/bun</string>',
  '\t\t<string>run</string>',
  '\t\t<string>/engine/src/cli/index.ts</string>',
  '\t\t<string>--repo</string>',
  '\t\t<string>/repo with space</string>',
  '\t\t<string>run</string>',
  '\t\t<string>demo</string>',
  '\t</array>',
  '',
  '\t<key>EnvironmentVariables</key>',
  '\t<dict>',
  '\t\t<key>PATH</key>',
  '\t\t<string>/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>',
  '\t\t<key>HOME</key>',
  '\t\t<string>/Users/x</string>',
  '\t</dict>',
  '',
  '\t<key>StartCalendarInterval</key>',
  '\t<array>',
  '\t\t<dict>',
  '\t\t\t<key>Minute</key>',
  '\t\t\t<integer>0</integer>',
  '\t\t\t<key>Hour</key>',
  '\t\t\t<integer>3</integer>',
  '\t\t</dict>',
  '\t\t<dict>',
  '\t\t\t<key>Minute</key>',
  '\t\t\t<integer>30</integer>',
  '\t\t\t<key>Hour</key>',
  '\t\t\t<integer>9</integer>',
  '\t\t\t<key>Weekday</key>',
  '\t\t\t<integer>1</integer>',
  '\t\t</dict>',
  '\t</array>',
  '',
  '\t<key>StandardOutPath</key>',
  '\t<string>/Users/x/Library/Logs/pipelines-demo.log</string>',
  '\t<key>StandardErrorPath</key>',
  '\t<string>/Users/x/Library/Logs/pipelines-demo.log</string>',
  '',
  '\t<key>RunAtLoad</key>',
  '\t<true/>',
  '</dict>',
  '</plist>',
  '',
].join('\n');

describe('launchdBackend.jobFiles', () => {
  test('generates the same plist, byte for byte, as before the interface', () => {
    const files = launchdBackend.jobFiles({
      pipelineName: 'demo',
      repoRoot: '/repo with space',
      bunPath: '/usr/local/bin/bun',
      cliEntry: '/engine/src/cli/index.ts',
      home: '/Users/x',
      path: '/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin',
      calendarIntervals: [
        ...cronToCalendarIntervals('0 3 * * *'),
        ...cronToCalendarIntervals('30 9 * * 1'),
      ],
      generatedAt: '2026-10-27T10:00:00.000Z',
      guards: [{ throttle: '46h' }],
    });
    expect(files).toEqual([
      {
        path: '/Users/x/Library/LaunchAgents/cat.start.pipelines.demo.plist',
        contents: EXPECTED_PLIST,
      },
    ]);
  });
});
