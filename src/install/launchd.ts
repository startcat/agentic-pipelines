/**
 * Render of the launchd plist from the schedules that `common.ts` computes,
 * and interpretation of the output of `launchctl print-disabled`.
 *
 * A PURE module on purpose: no I/O and no launchctl. The effects live in
 * src/install/launchctl.ts and `launchd-backend.ts` wraps them, which is all
 * the commands and the dashboard see. Same split as runner/fs-guard.ts, for
 * the same reason: the logic that decides is tested entirely without
 * touching the machine's system.
 */

import { join } from 'node:path';
import type { JobSpecInput } from './backend.ts';
import { grantsRunAtLoad, labelFor, type CalendarInterval } from './common.ts';

export type PlistSpec = {
  label: string;
  programArguments: string[];
  environmentVariables: Record<string, string>;
  calendarIntervals: CalendarInterval[];
  logPath: string;
  /** Path of the `pipeline.yaml` this plist comes from, for the header. */
  sourcePipelineYaml: string;
  generatedAt: string;
  /** Whether launchd should fire the job when the domain loads. See `grantsRunAtLoad`. */
  runAtLoad: boolean;
};

export function logPathFor(home: string, pipelineName: string): string {
  return join(home, 'Library', 'Logs', `pipelines-${pipelineName}.log`);
}

/**
 * Builds the `PlistSpec` from EXPLICIT inputs — no `homedir()` or
 * `process.execPath` in here. It lives in the pure module because it has two
 * consumers: `install`, which writes it, and the web dashboard, which
 * generates it only to compare it with the one on disk and decide whether
 * the installed job has drifted (`drifted` state). Two different generators
 * could disagree; a single one cannot.
 */
export function buildPlistSpec(input: JobSpecInput): PlistSpec {
  return {
    label: labelFor(input.pipelineName),
    programArguments: [
      input.bunPath, 'run', input.cliEntry,
      '--repo', input.repoRoot,
      'run', input.pipelineName,
    ],
    environmentVariables: { PATH: input.path, HOME: input.home },
    calendarIntervals: input.calendarIntervals,
    logPath: logPathFor(input.home, input.pipelineName),
    sourcePipelineYaml: join(input.repoRoot, 'pipelines', input.pipelineName, 'pipeline.yaml'),
    generatedAt: input.generatedAt,
    runAtLoad: grantsRunAtLoad(input.guards),
  };
}

function escapeXml(text: string): string {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

export function renderPlist(spec: PlistSpec): string {
  const args = spec.programArguments
    .map((arg) => `\t\t<string>${escapeXml(arg)}</string>`)
    .join('\n');

  const env = Object.entries(spec.environmentVariables)
    .map(([key, value]) => `\t\t<key>${escapeXml(key)}</key>\n\t\t<string>${escapeXml(value)}</string>`)
    .join('\n');

  const intervals = spec.calendarIntervals
    .map((interval) => {
      const entries = Object.entries(interval)
        .map(([key, value]) => `\t\t\t<key>${key}</key>\n\t\t\t<integer>${value}</integer>`)
        .join('\n');
      return entries === '' ? '\t\t<dict/>' : `\t\t<dict>\n${entries}\n\t\t</dict>`;
    })
    .join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!--
  GENERATED BY \`pipelines install\` — DO NOT EDIT BY HAND.
  Source:    ${escapeXml(spec.sourcePipelineYaml)}
  Generated: ${spec.generatedAt}

  To change the schedule, edit \`triggers.cron\` in that file and run
  \`pipelines install\` again. To change a parameter, edit
  \`.params.local.json\` in the data repo: this plist carries none.
-->
<plist version="1.0">
<dict>
\t<key>Label</key>
\t<string>${escapeXml(spec.label)}</string>

\t<key>ProgramArguments</key>
\t<array>
${args}
\t</array>

\t<key>EnvironmentVariables</key>
\t<dict>
${env}
\t</dict>

\t<key>StartCalendarInterval</key>
\t<array>
${intervals}
\t</array>

\t<key>StandardOutPath</key>
\t<string>${escapeXml(spec.logPath)}</string>
\t<key>StandardErrorPath</key>
\t<string>${escapeXml(spec.logPath)}</string>

\t<key>RunAtLoad</key>
\t${spec.runAtLoad ? '<true/>' : '<false/>'}
</dict>
</plist>
`;
}

/**
 * Labels marked `disabled` in the output of `launchctl print-disabled`.
 * The format is `"<label>" => disabled` or `=> enabled`, one per line.
 *
 * Format VERIFIED LIVE, not assumed: by running
 * `launchctl print-disabled gui/501` on macOS Darwin 25.6, whose real output
 * is `"<label>" => enabled` / `=> disabled`, one entry per line, exactly what
 * this parser expects.
 */
export function parseDisabledLabels(stdout: string): string[] {
  const labels: string[] = [];
  for (const line of stdout.split('\n')) {
    const match = /"([^"]+)"\s*=>\s*disabled/.exec(line);
    if (match) labels.push(match[1]!);
  }
  return labels;
}
